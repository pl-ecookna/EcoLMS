from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class PromptDefinition:
    module: str
    key: str
    title: str
    system_prompt: str
    user_prompt_template: str = ""

    @property
    def text(self) -> str:
        return self.system_prompt


